function detailLinks(project) {
  const links = [];
  if (project.links.repo) {
    links.push(`<a href="${project.links.repo}" target="_blank" rel="noreferrer"><span>${uiCopy[state.language].detail.repository}</span><b>↗</b></a>`);
  }
  if (project.links.demo) {
    links.push(`<a href="${project.links.demo}" target="_blank" rel="noreferrer"><span>${uiCopy[state.language].detail.demo}</span><b>↗</b></a>`);
  }
  return links.length
    ? `<section><h4>${uiCopy[state.language].detail.links}</h4><div class="detail-links">${links.join("")}</div></section>`
    : `<section><h4>${uiCopy[state.language].detail.links}</h4><p>${uiCopy[state.language].projects.privateCode}</p></section>`;
}

